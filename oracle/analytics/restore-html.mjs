// Render a restore map (restore.mjs's markdown) to a self-contained HTML worklist.
//
//   node oracle/analytics/restore-html.mjs [report.md] [-o out.html]
//     report.md   default: the newest findings/*-driver-restore.md
//     -o          default: the input path with .html
//
// Why a second file rather than plain markdown: the restore is done with the game open, and a
// browser shows a .md as unstyled text. This adds a tick box per line with a progress bar, greys out
// a champion once every line under it is ticked, and gives a sidebar to jump between them.
//
// The page is SELF-CONTAINED — CSS and JS inlined, no external requests — because it is opened over
// a \\wsl.localhost UNC path where a CDN reference is both a privacy leak and a broken-offline risk.
//
// Ticks are a local scratch aid, NOT the source of truth. The snapshots are: re-running restore.mjs
// re-derives what is left from the DB. Ticks are keyed on the artifact id so they survive a
// regeneration even though champion ordering shifts as slots close.

import { readFileSync, readdirSync, realpathSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const FINDINGS = fileURLToPath(new URL("./findings", import.meta.url));

const ESC = { "&": "&amp;", "<": "&lt;", ">": "&gt;" };
const esc = (s) => s.replace(/[&<>]/g, (c) => ESC[c]);

// Inline spans: `code` first so bold markers inside a code span are left alone.
export function inline(s) {
  return esc(s)
    .replace(/`([^`]+)`/g, (_, c) => `<code>${c}</code>`)
    .replace(/\*\*([^*]+)\*\*/g, (_, b) => `<strong>${b}</strong>`);
}

// A deliberately small markdown subset — headings, nested bullets, bold, inline code — rather than a
// parser dependency. The input is not arbitrary markdown: it is generated by restore.mjs next door,
// so the shape is fixed and known, and `marked` is a packages/web dependency that an oracle/ script
// would only reach through npm hoisting.
export function toHtml(md) {
  const out = [];
  let list = 0;                                     // open <ul> depth
  const closeTo = (depth) => { while (list > depth) { out.push("</ul>"); list--; } };
  for (const raw of md.split("\n")) {
    const h = /^(#{1,3}) (.+)$/.exec(raw);
    if (h) { closeTo(0); out.push(`<h${h[1].length}>${inline(h[2])}</h${h[1].length}>`); continue; }
    const li = /^(\s*)- (.+)$/.exec(raw);
    if (li) {
      const depth = Math.floor(li[1].length / 2) + 1;
      // A nested list opens INSIDE the line above it, so the parent <li> is left unclosed until the
      // nesting unwinds — that containment is what the page's checkbox pass keys on.
      while (list < depth) { out.push("<ul>"); list++; }
      closeTo(depth);
      out.push(`<li>${inline(li[2])}`);
      continue;
    }
    if (!raw.trim()) { closeTo(0); continue; }
    // A bare continuation line belongs to whatever is open above it.
    if (list > 0) out.push(` ${inline(raw.trim())}`);
    else out.push(`<p>${inline(raw.trim())}</p>`);
  }
  closeTo(0);
  return out.join("\n");
}

