function newestReport() {
  const hits = readdirSync(FINDINGS).filter((f) => /-driver-restore\.md$/.test(f)).sort();
  return hits.length ? `${FINDINGS}/${hits[hits.length - 1]}` : null;
}

function main() {
  const argv = process.argv.slice(2);
  let src = null, out = null;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "-o") out = argv[++i];
    else if (argv[i]) src = argv[i];
  }
  src = src ?? newestReport();
  if (!src) {
    console.error(`no *-driver-restore.md in ${FINDINGS}; run restore.mjs first`);
    process.exit(1);
  }
  const md = readFileSync(src, "utf8");
  const h1 = /^# (.+)$/m.exec(md);
  const title = h1 ? h1[1] : "Gear restore map";
  const dest = out ?? src.replace(/\.md$/, ".html");
  writeFileSync(dest, page(md, title));
  console.log(`wrote ${dest}`);
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) main();
